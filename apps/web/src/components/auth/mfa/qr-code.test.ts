function render(text: string) {
  const { size, modules } = encodeQr(text)
  return modules.map((row) => row.map((on) => (on ? '#' : '.')).join('')).slice(0, size)
}

describe('encodeQr', () => {
  it('matches the reference encoder for a short version 1 code', () => {
    expect(render(HELLO_TEXT)).toEqual(HELLO_ROWS)
  })

  it('matches the reference encoder for a version 6 otpauth URI', () => {
    expect(render(OTPAUTH_TEXT)).toEqual(OTPAUTH_ROWS)
  })

  it('uses the published format string for level L', () => {
    expect(formatBits(0)).toBe(0b111011111000100)
    expect(formatBits(7)).toBe(0x6976)
  })
})
